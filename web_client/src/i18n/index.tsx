// Sort phrase replacements longest-first once at startup so complete sentences/headings
// are always matched before shorter sub-phrases.
const SORTED_PHRASE_REPLACEMENTS: Record<
  Exclude<SupportedLocale, "es">,
  Array<[string, string]>
> = {
  en: [...PHRASE_REPLACEMENTS.en].sort((a, b) => b[0].length - a[0].length),
  pt: [...PHRASE_REPLACEMENTS.pt].sort((a, b) => b[0].length - a[0].length),
  it: [...PHRASE_REPLACEMENTS.it].sort((a, b) => b[0].length - a[0].length),
  de: [...PHRASE_REPLACEMENTS.de].sort((a, b) => b[0].length - a[0].length),
  ja: [...PHRASE_REPLACEMENTS.ja].sort((a, b) => b[0].length - a[0].length),
  fr: [...PHRASE_REPLACEMENTS.fr].sort((a, b) => b[0].length - a[0].length),
  ko: [...PHRASE_REPLACEMENTS.ko].sort((a, b) => b[0].length - a[0].length),
  zh: [...PHRASE_REPLACEMENTS.zh].sort((a, b) => b[0].length - a[0].length),
};

export function translateDynamicPhrase(
  rawText: string,
  locale: SupportedLocale
): string {
  if (!rawText || locale === "es") return rawText;
  const table = SORTED_PHRASE_REPLACEMENTS[locale];
  if (!table) return rawText;
  let result = rawText;
  for (const [esFragment, localizedFragment] of table) {
    if (result.includes(esFragment)) {
      result = result.split(esFragment).join(localizedFragment);
    }
  }
  return result;
}

const originalTextNodeMap = new WeakMap<Node, string>();
const lastAppliedTextNodeMap = new WeakMap<Node, string>();

/**
 * Automatically localizes any rendered text nodes inside the root container when a
 * non-Spanish locale is selected, while respecting React-managed `{t(...)}` updates
 * so that already-translated React text nodes are NEVER overwritten back to Spanish.
 */
export function applyDomSubtreeLocalization(
  root: HTMLElement | null,
  locale: SupportedLocale
): void {
  if (!root || typeof document === "undefined") return;

  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let currentNode: Node | null = walker.nextNode();
  while (currentNode) {
    const parentTag = currentNode.parentElement?.tagName;
    if (
      parentTag !== "SCRIPT" &&
      parentTag !== "STYLE" &&
      parentTag !== "CODE"
    ) {
      const currentVal = currentNode.nodeValue || "";
      if (currentVal.trim().length > 0) {
        let baseEs = originalTextNodeMap.get(currentNode);
        const lastApplied = lastAppliedTextNodeMap.get(currentNode);

        // If React updated this Text node since our last pass (currentVal !== lastApplied),
        // adopt React's fresh value so we never clobber `{t(...)}` re-renders!
        if (baseEs === undefined || (lastApplied !== undefined && currentVal !== lastApplied)) {
          baseEs = currentVal;
          originalTextNodeMap.set(currentNode, baseEs);
        }

        const nextVal =
          locale === "es" ? baseEs : translateDynamicPhrase(baseEs, locale);
        if (nextVal !== currentVal) {
          currentNode.nodeValue = nextVal;
        }
        lastAppliedTextNodeMap.set(currentNode, nextVal);
      }
    }
    currentNode = walker.nextNode();
  }
}

export interface I18nContextValue {
  locale: SupportedLocale;
  setLocale: (next: SupportedLocale) => void;
  t: (key: UiTranslationKey) => string;
  tr: (rawText: string) => string;
  locales: LocaleMeta[];
}

const I18nContext = createContext<I18nContextValue>({
  locale: "es",
  setLocale: () => {},
  t: (key) => UI_DICTIONARIES.es[key] || key,
  tr: (rawText) => rawText,
  locales: SUPPORTED_LOCALES,
});

export const I18nProvider: React.FC<{
  initialLocale?: SupportedLocale;
  children: React.ReactNode;
}> = ({ initialLocale, children }) => {
  const [locale, setLocaleState] = useState<SupportedLocale>(() =>
    initialLocale ? initialLocale : detectInitialLocale()
  );

  const setLocale = (next: SupportedLocale) => {
    if (!isSupportedLocale(next)) return;
    saveLocalePreference(next);
    setLocaleState(next);
  };

  useEffect(() => {
    saveLocalePreference(locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => {
    const dict = UI_DICTIONARIES[locale] || UI_DICTIONARIES.es;
    return {
      locale,
      setLocale,
      t: (key: UiTranslationKey) =>
        dict[key] ?? UI_DICTIONARIES.es[key] ?? key,
      tr: (rawText: string) => translateDynamicPhrase(rawText, locale),
      locales: SUPPORTED_LOCALES,
    };
  }, [locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
};

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
